import json
from pathlib import Path
import re
import tempfile
import unittest
from unittest.mock import patch
import zipfile

from tools import gen_version_consts as gen
from tools import lab

INFO = {
    "id": "26.4", "name": "26.4", "world_version": 5100, "protocol_version": 780,
    "pack_version": {"resource_major": 99, "resource_minor": 0, "data_major": 124, "data_minor": 2},
    "build_time": "2026-12-01T09:05:07+00:00", "java_version": 25, "stable": False,
}


class GenVersionConstsTests(unittest.TestCase):
    def test_legacy_1_20_1_pack_formats_generate_rust_constants(self):
        info = {**INFO, "id": "1.20.1", "name": "1.20.1", "world_version": 3465,
                "protocol_version": 763, "java_version": 17, "stable": True,
                "build_time": "2023-06-12T13:23:26+00:00",
                "pack_version": {"resource": 15, "data": 15}}
        text = gen.render(info)
        for line in ['pub const VANILLA_VERSION: &str = "1.20.1";',
                     'pub const PROTOCOL_VERSION: i32 = 763;',
                     'pub const DATA_VERSION: i32 = 3465;',
                     'pub const RESOURCE_PACK_FORMAT: (i64, i64) = (15, 0);',
                     'pub const DATA_PACK_FORMAT: (i64, i64) = (15, 0);',
                     'pub const JAVA_VERSION: u32 = 17;']:
            self.assertIn(line, text)

    def test_missing_pack_format_is_not_generated_as_a_version(self):
        with self.assertRaisesRegex(ValueError, "data pack version"):
            gen.render({**INFO, "pack_version": {"resource": 15}})

    def test_older_single_pack_format_is_kept_for_both_kinds(self):
        text = gen.render({**INFO, "pack_version": 6})
        self.assertIn("pub const RESOURCE_PACK_FORMAT: (i64, i64) = (6, 0);", text)
        self.assertIn("pub const DATA_PACK_FORMAT: (i64, i64) = (6, 0);", text)

    def test_renders_every_fact(self):
        text = gen.render(INFO)
        for line in ['pub const VERSION_ID: &str = "26.4";', 'pub const VANILLA_VERSION: &str = "26.4";',
                     "pub const PROTOCOL_VERSION: i32 = 780;", "pub const DATA_VERSION: i32 = 5100;",
                     "pub const RESOURCE_PACK_FORMAT: (i64, i64) = (99, 0);",
                     "pub const DATA_PACK_FORMAT: (i64, i64) = (124, 2);", "pub const JAVA_VERSION: u32 = 25;",
                     "pub const STABLE: bool = false;", 'pub const BUILD_TIME: &str = "Tue Dec 01 09:05:07 UTC 2026";']:
            self.assertIn(line, text)

    def test_build_time_is_printed_in_utc(self):
        self.assertEqual(gen.java_date("2026-09-15T13:20:48+02:00"), "Tue Sep 15 11:20:48 UTC 2026")

    def test_reads_the_jar(self):
        with tempfile.TemporaryDirectory() as directory:
            jar = Path(directory) / "client.jar"
            with zipfile.ZipFile(jar, "w") as archive:
                archive.writestr("version.json", json.dumps(INFO))
            self.assertEqual(lab.version_info(jar), INFO)

    def test_other_version_cannot_overwrite_the_active_engine_constants(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            jar = root / "client.jar"
            with zipfile.ZipFile(jar, "w") as archive:
                archive.writestr("version.json", json.dumps({**INFO, "id": "1.20.1"}))
            out, lock = root / "version.rs", root / "research-lock.json"
            out.write_text("active 26.3", encoding="utf-8")
            lock.write_text(json.dumps({"minecraft": {"version": "26.3"}}), encoding="utf-8")
            with patch.object(gen, "OUT", out), patch.object(gen.lab, "LOCK", lock), \
                    patch("sys.argv", ["gen_version_consts.py", "--jar", str(jar)]):
                with self.assertRaisesRegex(SystemExit, "Refusing to overwrite"):
                    gen.main()
            self.assertEqual(out.read_text(encoding="utf-8"), "active 26.3")

    def test_committed_file_is_the_pinned_version(self):
        """A pin bump regenerates version.rs: the lock and the constants never disagree."""
        text = gen.OUT.read_text()
        pinned = json.loads(lab.LOCK.read_text())["minecraft"]
        self.assertEqual(re.search(r'VANILLA_VERSION: &str = "([^"]+)"', text)[1], pinned["version"])
        self.assertEqual(int(re.search(r"JAVA_VERSION: u32 = (\d+)", text)[1]), pinned["java_major"])
        self.assertIn("Generated by tools/gen_version_consts.py", text)


if __name__ == "__main__":
    unittest.main()
